import type { Choice, Question, QType, TopicId } from './types';

const LETTERS = ['a', 'b', 'c', 'd', 'e', 'f'] as const;

function q(
  id: string,
  topic: TopicId,
  type: QType,
  prompt: string,
  options: string[],
  answer: number[],
  explain: string,
): Question {
  const choices: Choice[] = options.map((text, i) => ({ id: LETTERS[i], text }));
  return {
    id,
    topic,
    type,
    prompt,
    options: choices,
    answer: answer.map((i) => LETTERS[i]),
    explain,
  };
}

