export function bankStats(list: Question[] = QUESTIONS) {
  const byTopic: Record<string, number> = {};
  const byType: Record<string, number> = {};
  const byTopicType: Record<string, number> = {};
  for (const item of list) {
    byTopic[item.topic] = (byTopic[item.topic] ?? 0) + 1;
    byType[item.type] = (byType[item.type] ?? 0) + 1;
    const key = `${item.topic}:${item.type}`;
    byTopicType[key] = (byTopicType[key] ?? 0) + 1;
  }
  return { total: list.length, byTopic, byType, byTopicType };
}
